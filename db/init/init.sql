CREATE TABLE IF NOT EXISTS medical_examination_types (
    id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                 varchar(255) NOT NULL CONSTRAINT medical_examination_types_name_key UNIQUE,
