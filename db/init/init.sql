INSERT INTO appointments (appointment_date, status, medical_examination_type_id, patient_id)
WITH slots AS (
    SELECT t.id AS type_id,
           g.day::date AS day,
           t.open_time,
           t.examination_duration,
           s.n + (extract(doy FROM g.day)::int % 3) AS slot_number   -- slot diversi giorno per giorno
    FROM medical_examination_types t
    CROSS JOIN generate_series(CURRENT_DATE - 6, CURRENT_DATE + 6, interval '1 day') AS g(day)
    JOIN days_of_week w
      ON w.examination_type_id = t.id
     AND w.day_of_week = (ARRAY['MONDAY', 'TUESDAY', 'WEDNESDAY', 'THURSDAY', 'FRIDAY', 'SATURDAY', 'SUNDAY'])
                         [extract(isodow FROM g.day)::int]
    CROSS JOIN (VALUES (0), (2)) AS s(n)
),
numbered AS (
    SELECT *, row_number() OVER (ORDER BY day, type_id, slot_number) AS rn
    FROM slots
)
SELECT day + open_time + slot_number * examination_duration * interval '1 minute',
       CASE
           WHEN day < CURRENT_DATE THEN CASE WHEN rn % 6 = 0 THEN 'CANCELLED' ELSE 'WAITING_FOR_REPORT' END
           WHEN day = CURRENT_DATE THEN 'CONFIRMED'
           WHEN rn % 7 = 0 THEN 'CANCELLED'
           WHEN rn % 2 = 0 THEN 'WAITING_FOR_CONFIRMATION'
           ELSE 'CONFIRMED'
       END,
       type_id,
       rn % 12 + 1
FROM numbered
ORDER BY rn;


